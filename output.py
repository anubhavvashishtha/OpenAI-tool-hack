    '            bank.clear()',
    '            bank_seen.clear()',
    '',
    '        for rep in range(PROBE_REPS):',
    '            print("\\n--- PROBE ROUND %d/%d ---" % (rep + 1, PROBE_REPS))',
    '            for ti in range(len(templates)):',
    '                if not _time_left(margin_s):',
    '                    print("[PROBE] Deadline approaching. Stopping probe loop early.")',
    '                    break',
    '',
    '                print("\\n  [Testing] Template: %s" % templates[ti][0])',
    '                fired, elapsed, n_exfil = _trial(ti, probe_index)',
    '                probe_index += 1',
    '',
    '                status = "FIRED (exfil=%d)" % n_exfil if fired else "FAILED"',
    '                print("  => Result: %-16s | Latency: %.2fs" % (status, elapsed))',
    '',
    '        selected = FALLBACK_INDEX',
    '        selected_rate = -1.0',
    '        for ti in range(len(templates)):',
    '            sc = len(latencies[ti])',
    '            fire_rate = fires[ti] / sc if sc else 0.0',
    '            if sc < PROBE_REPS or fire_rate < MIN_FIRE_RATE:',
    '                continue',
    '            total_time = sum(latencies[ti]) or LAT_FLOOR_S',
    '            rate = raw_score[ti] / total_time',
    '            if rate > selected_rate:',
    '                selected, selected_rate = ti, rate',
    '',
    '        print("\\n[ATTACK] Probing complete.")',
    '        print("[ATTACK] Winner: %s | Rate: %.3f" % (templates[selected][0], selected_rate))',
    '        for ti in range(len(templates)):',
    '            print("  - %-30s: fires=%d/%d | raw_score=%d" % (templates[ti][0], fires[ti], len(latencies[ti]), raw_score[ti]))',
    '',
    '        if selected_rate < 0:',
    '            print("[ATTACK] No templates succeeded during probing. Aborting fill phase.")',
    '            return findings',
    '',
    '        # ══════════════════════════════════════════════════════════════════════',
    '        # PHASE 3 — Fill Loop',
    '        # ══════════════════════════════════════════════════════════════════════',
    '        sel_bank = [e for e in bank if e[0] == selected]',
    '        seed_bank = sel_bank if sel_bank else bank',
    '',
    '        for ti, index, elapsed in seed_bank:',
    '            msg = _msg(templates[ti][1], index)',
    '            if msg not in returned_seen:',
    '                findings.append(_candidate(templates[ti][1], index))',
    '                returned_seen.add(msg)',
    '                replay_cost += elapsed',
    '',
    '        sf = fire_latencies[selected]',
    '        fill_unit = (',
    '            _median(sf)',
    '            if sf',
    '            else (_median(latencies[selected]) if latencies[selected] else slowest)',
    '        )',
    '        if fill_unit <= 0 or fill_unit == float("inf"):',
    '            fill_unit = slowest',
    '',
    '        sel_template = templates[selected][1]',
    '        fill_index = 0',
    '',
    '        while (',
    '            replay_cost + fill_unit <= replay_cap',
    '            and len(findings) < MAX_CANDIDATES',
    '            and _time_left(margin_s, slowest)',
    '        ):',
    '            ci = fill_index',
    '            fill_index += 1',
    '            msg = _msg(sel_template, ci)',
    '            if msg in returned_seen:',
    '                continue',
    '',
    '            # Silent trial execution',
    '            t0 = time.monotonic()',
    '            n_exfil = 0',
    '            try:',
