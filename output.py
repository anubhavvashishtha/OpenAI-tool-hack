    '                for turn in msg:',
    '                    _interact(turn)',
    '                    # Same reasoning as _trial(): keep running every turn so',
    '                    # n_exfil reflects the TRUE full-candidate count, not',
    '                    # just whichever turn happened to fire first.',
    '                    n_exfil = _count_exfil(env.export_trace_dict())',
    '            except Exception:',
    '                pass # Do not reset n_exfil on exception',
    '',
    '            fired = n_exfil > 0',
    '            elapsed = max(LAT_FLOOR_S, time.monotonic() - t0)',
    '',
    '            replay_cost += elapsed',
    '',
    '            if fired:',
    '                findings.append(_candidate(sel_template, ci))',
    '                returned_seen.add(msg)',
    '',
    '        if replay_cost > replay_cap and len(findings) > 1:',
    '            keep = max(1, int(len(findings) * (replay_cap / replay_cost)))',
    '            findings = findings[:keep]',
    '',
    '        try:',
    '            print("\\n[ATTACK] Done | model=%s | selected=%s | returned=%d candidates | replay_cost=%.0fs/%.0fs" % (',
    '                model_label, templates[selected][0], len(findings), replay_cost, replay_cap',
    '            ))',
    '        except Exception:',
    '            pass',
    '',
    '        return findings[:MAX_CANDIDATES]',
